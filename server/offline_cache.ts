import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

// Offline play: the build writes sw.js, a service worker that saves the whole
// game (page, code, art, icons) on the device, so Story and Battle vs Bot open
// with no connection. Rooms (/room/CODE) and the leaderboard (/api/) always go
// to the network. The page itself is network first, so updates arrive as soon
// as the player is online; everything else is cache first (file names carry a
// content hash). A new build gets a new cache and the old one is deleted.

/** Builds sw.js for this build's files (paths relative to the page, e.g. 'assets/index-abc.js'). */
export function serviceWorkerSource(version: string, files: readonly string[]): string {
  return `// Generated by server/offline_cache.ts at build time. Do not edit.
const CACHE = 'spaceblast-' + ${JSON.stringify(version)};
const FILES = ${JSON.stringify(['./', ...files])};
const PAGE_WAIT_MS = 4000;
const scope = self.registration.scope;
const at = (file) => new URL(file, scope).href;
// Saved files are matched by URL alone: hosts may send Vary: Origin, and module
// scripts carry an Origin header the install requests didn't.
const MATCH = { ignoreSearch: true, ignoreVary: true };

// 'reload' skips the HTTP cache, so a host with long cache times can't hand us stale files.
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(at(f), { cache: 'reload' })))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('spaceblast-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

/** Online rooms and the leaderboard never come from the cache. */
function live(url) {
  return url.pathname.includes('/api/') || /\\/room\\/[A-Z]+$/.test(url.pathname);
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || !req.url.startsWith(scope)) return;
  if (live(new URL(req.url))) return;
  e.respondWith(req.mode === 'navigate' ? page(req) : file(req));
});

/** The page: the network when it answers well and in time, else the saved copy. */
async function page(req) {
  const saved = () => caches.match(at('./'), MATCH);
  // A host error (404, 5xx) shouldn't hide a game that can run offline.
  const net = fetch(req).then(async (res) => (res.ok ? res : (await saved()) || res));
  let timer;
  const late = new Promise((done) => { timer = setTimeout(() => saved().then((s) => s && done(s)), PAGE_WAIT_MS); });
  try {
    return await Promise.race([net, late]);
  } catch {
    return (await saved()) || Response.error();
  } finally {
    clearTimeout(timer);
  }
}

async function file(req) {
  return (await caches.match(req, MATCH)) || fetch(req);
}
`;
}

/** Every file under dir, as forward-slash paths relative to it. */
function filesIn(dir: string): string[] {
  try {
    return readdirSync(dir).flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? filesIn(path).map((f) => `${name}/${f}`) : [name];
    });
  } catch {
    return [];
  }
}

/** Short version id: changes whenever any saved file's name or content changes. */
export function cacheVersion(files: ReadonlyArray<readonly [string, string | Uint8Array]>): string {
  const hash = createHash('sha256');
  for (const [name, content] of [...files].sort((a, b) => (a[0] < b[0] ? -1 : 1))) hash.update(name).update('\0').update(content).update('\0');
  return hash.digest('hex').slice(0, 12);
}

export function offlineCache(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'spaceblast-offline-cache',
    apply: 'build',
    configResolved(c) { config = c; },
    generateBundle(_options, bundle) {
      if (config.build.ssr) return; // the Fly server build is not a page
      const files: Array<[string, string | Uint8Array]> = [];
      for (const out of Object.values(bundle)) {
        if (out.fileName.endsWith('.map')) continue;
        files.push([out.fileName, out.type === 'chunk' ? out.code : out.source]);
      }
      if (config.publicDir && config.build.copyPublicDir) {
        for (const f of filesIn(config.publicDir)) files.push([f, readFileSync(join(config.publicDir, f))]);
      }
      // The page is saved as './' (hosts may redirect /index.html to /).
      const saved = files.map(([name]) => name).filter((name) => name !== 'index.html' && name !== 'sw.js').sort();
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorkerSource(cacheVersion(files), saved) });
    },
  };
}
